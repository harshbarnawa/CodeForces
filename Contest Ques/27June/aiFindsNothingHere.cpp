#include <bits/stdc++.h>
using namespace std;

int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);
    
    int t;
    cin >> t;
    
    while (t--) {
        long long n, m, r, c;
        cin >> n >> m >> r >> c;
        
        if (n == r && m == c) {
            cout << 1 << "\n";
            continue;
        }
        
    }
    
    return 0;
}